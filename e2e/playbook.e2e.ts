test('resizes and remembers each sidebar while protecting the main workspace', async ({ page }) => {
  await page.setViewportSize({ width: 1720, height: 900 })
  await page.goto('/topics/cdc/content')
  const workspace = page.getByRole('complementary', { name: 'Workspace navigation' })
  const topics = page.getByRole('complementary', { name: 'Topic browser' })
  const main = page.getByRole('main')
  const workspaceHandle = page.getByRole('separator', { name: 'Resize Workspace navigation' })
  const topicsHandle = page.getByRole('separator', { name: 'Resize Topics sidebar' })
  const width = (panel: typeof workspace) => panel.evaluate(element => element.getBoundingClientRect().width)
  const startingWorkspace = await width(workspace)
  const startingTopics = await width(topics)
  expect(startingWorkspace).toBe(255)
  expect(startingTopics).toBe(318)

  async function drag(handle: typeof workspaceHandle, distance: number, duringDrag: () => Promise<void>) {
    await handle.hover()
    await expect(handle).toHaveCSS('cursor', 'col-resize')
    const box = (await handle.boundingBox())!
    const x = box.x + box.width / 2
    await page.mouse.move(x, 180)
    await page.mouse.down()
    try {
      await page.mouse.move(Math.max(1, x + distance), 180, { steps: 8 })
      await duringDrag()
      await expect(main).toHaveCSS('user-select', 'none')
    } finally {
      await page.mouse.up()
    }
  }
  await drag(workspaceHandle, 450, async () => {
    await expect.poll(() => width(workspace)).toBe(400)
    expect(await width(topics)).toBe(startingTopics)
  })
  await drag(topicsHandle, 420, async () => {
    await expect.poll(() => width(topics)).toBe(600)
    expect(await width(workspace)).toBe(400)
  })
  expect(await width(main)).toBeGreaterThanOrEqual(700)
  await page.reload()
  await expect(workspaceHandle).toHaveAttribute('aria-valuenow', '400')
  await expect(topicsHandle).toHaveAttribute('aria-valuenow', '600')
  const layoutKey = 'playbook.layout.sidebar-widths'
  await page.setViewportSize({ width: 1320, height: 900 })
  await expect.poll(() => width(main)).toBe(700)
  await expect(topicsHandle).toHaveAttribute('aria-valuemax', '220')
  await drag(topicsHandle, 280, async () => {
    expect(await width(topics)).toBe(220)
    expect(await width(main)).toBe(700)
  })
  await page.setViewportSize({ width: 1720, height: 900 })
  await expect(topicsHandle).toHaveAttribute('aria-valuenow', '600')
  await workspaceHandle.dblclick()
  await expect.poll(() => width(workspace)).toBe(startingWorkspace)
  expect(await width(topics)).toBe(600)
  await topicsHandle.dblclick()
  await expect.poll(() => width(topics)).toBe(startingTopics)
  await page.evaluate(key => localStorage.setItem(key, JSON.stringify({ workspace: 900, topics: -40 })), layoutKey)
  await page.reload()
  await expect(workspaceHandle).toHaveAttribute('aria-valuenow', '400')
  await expect(topicsHandle).toHaveAttribute('aria-valuenow', '200')
  await workspaceHandle.press('Home')
  await expect(workspaceHandle).toHaveAttribute('aria-valuenow', '180')

  for (const viewport of [1024, 800, 390]) {
    await page.setViewportSize({ width: viewport, height: 900 })
    await expect(workspace).toBeHidden()
    if (viewport < 900) await expect(topicsHandle).toHaveCount(0)
    expect(await main.evaluate(element => element.getBoundingClientRect().width)).toBeGreaterThanOrEqual(Math.min(700, viewport))
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(viewport)
  }
  await topics.getByRole('button', { name: 'Hide list' }).click()
  await expect(topics.getByRole('link', { name: 'Apache Kafka' })).toBeHidden()
  await topics.getByRole('button', { name: 'Show list' }).click()
  await topics.getByRole('link', { name: 'Apache Kafka' }).click()
  await expect(main.getByRole('heading', { name: 'Apache Kafka', exact: true })).toBeVisible()
})

