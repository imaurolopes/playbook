test('keeps project card statuses and percentages aligned at narrow and wide widths', async ({ page }) => {
  await page.goto('/projects')
  await expect(page.getByRole('heading', { name: 'Projects', exact: true })).toBeVisible()
  await page.evaluate(key => {
    const workspace = JSON.parse(localStorage.getItem(key)!)
    workspace.version = 5
    const data = workspace.implementationData
    const timestamps = { createdAt: '2026-11-19T12:00:00.000Z', updatedAt: '2026-11-19T12:00:00.000Z' }
    const fixtures = [
      { id: 'empty', name: 'Empty project', statuses: [] },
      { id: 'pending', name: 'Pending project ' + 'long title '.repeat(24), statuses: ['todo'] },
      { id: 'active', name: 'Active project', statuses: ['in_progress', 'blocked', 'done'] },
      { id: 'complete', name: 'Complete project', statuses: ['done'] },
    ]
    data.projects = fixtures.map(({ id, name }) => ({ id, name, description: id === 'pending' ? 'Long description '.repeat(24) : '', ...timestamps }))
    data.implementations = fixtures.filter(item => item.statuses.length).map(({ id }) => ({
      id, projectId: id, topicId: 'cdc', status: 'not_started', environment: 'development', notes: '', ...timestamps,
    }))
    data.tasks = fixtures.flatMap(({ id, statuses }) => statuses.map((status, order) => ({
      id: id + order, implementationId: id, title: id + order, description: '', order, status,
      criteria: [], dependencyIds: [], references: [], ...timestamps,
    })))
    localStorage.setItem(key, JSON.stringify(workspace))
  }, storageKey)
  await page.reload()

  const cases = [
    ['Empty project', 'Not planned', '0'], ['Pending project', 'Planned', '0'],
    ['Active project', 'In progress', '33'], ['Complete project', 'Completed', '100'],
  ] as const
  for (const [name, status, value] of cases) {
    const card = page.locator('.project-list-card').filter({ has: page.getByRole('link', { name }) })
    await expect(card.getByText(status, { exact: true })).toBeVisible()
    await expect(card.getByRole('progressbar')).toHaveAttribute('value', value)
    await expect(card.locator('.project-progress > span')).toHaveText(value + '%')
  }

  for (const width of [320, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    const layout = await page.locator('.project-list-card').evaluateAll(cards => cards.map(card => {
      const bounds = card.getBoundingClientRect()
      const bar = card.querySelector('progress')!.getBoundingClientRect()
      const label = card.querySelector('.project-progress > span')!
      const value = label.getBoundingClientRect()
      const text = document.createRange()
      text.selectNodeContents(label)
      const badge = card.querySelector('.project-status')!.getBoundingClientRect()
      return { barWidth: bar.width, oneLine: new Set(Array.from(text.getClientRects(), rect => rect.top)).size === 1,
        badgeRight: Math.round(bounds.right - badge.right),
        fits: bar.right <= value.left && value.right <= bounds.right && badge.right <= bounds.right }
    }))
    expect(layout).toHaveLength(4)
    for (const card of layout) {
      expect(card.barWidth).toBeGreaterThan(0)
      expect(card.oneLine && card.fits).toBe(true)
      expect(card.badgeRight).toBe(layout[0].badgeRight)
    }
  }
})

