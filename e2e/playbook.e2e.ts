  await page.goto('/topics/apache-kafka/dependencies')
  await page.getByRole('button', { name: 'Add relationship' }).click()
  const add = page.getByRole('dialog', { name: 'Add relationship' })
  await add.getByRole('searchbox').fill('CDC')
  await add.getByRole('button', { name: 'Change Data Capture (CDC)', exact: true }).click()
